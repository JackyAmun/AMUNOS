static int note_frequency(int note)
{
    if (note < 0) {
        if (note < -7) return -1;
        return note_freq[-note] / 2;
    }
    if (note == 0) return 0;
    if (note <= 7) return note_freq[note];
    if (note <= 13) return note_freq[note % 7] * 2;
    return -1;
}

static unsigned note_duration_ms(unsigned divisor)
{
    if (!divisor) return 0;
    return 1920u / divisor;
}

int main(void)
{
    unsigned count = sizeof(song) / sizeof(song[0]);
    unsigned i;
    printf("AMUNOS MUSIC: %u notes\n", count);
    for (i = 0; i < count; i++) {
        unsigned duration = note_duration_ms(div[i]);
        int frequency = note_frequency(song[i]);
        if (!duration || frequency < 0) {
            printf("Invalid score entry %u\n", i);
            return 1;
        }
        if (frequency > 0) {
            if (sys_beep((unsigned)frequency, duration) != 0) {
                printf("Speaker error at note %u (%d Hz)\n", i, frequency);
                return 1;
            }
        } else {
            sys_sleep((duration + 9) / 10);
        }
    }
    printf("Playback complete.\n");
    return 0;
}
